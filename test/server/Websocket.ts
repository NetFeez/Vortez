suite.add('Testing automated Ping/Pong Websocket.Response.', async (test) => {
    const { client, server } = await Websocket.WebSocketPair({ autoAcceptRequest: true });

    return test.awaitEvent<void>(async (done) => {
        server.on('error', (error) => {
            test.done('Server websocket connection error: ' + error.message, error);
            done();
        });
        client.on('error', (error) => {
            test.done('Client websocket connection error: ' + error.message, error);
            done();
        });
        client.on('pong', (data) => {
            test.info('Client received pong from server');
        });
        
        const customPingPromise = new Promise<void>((done) => {
            server.once('ping', (data) => {
                test.info('Server received ping from client');
                const text = data.toString('utf-8');
                test.expect(text).equals('ping with custom data!', 'Ping payload should match the sent data');
                done();
            });
        });

        const data = Buffer.from('ping with custom data!', 'utf-8');
        client.write(data, 0x9);
        await customPingPromise;

        server.once('ping', (data) => {
            test.info('Server received ping from client');
            const text = data.toString('utf-8');
            test.expect(text.length).equals(36, 'Ping payload should be 36 characters long');
        });

        const ping = await client.ping();
        test.info(`Ping round-trip time: ${ping} ms`);
        test.expect(ping < 1000).ok('Ping round-trip time should be less than 1000 ms');
        test.done('Ping/Pong test passed');
        done();
    }, 1000);
});

